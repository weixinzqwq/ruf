"""Build a version-bound display patch and reproduce the runtime's edit table."""
import argparse
from pathlib import Path
import shutil
import struct
import subprocess

from observe_skin_motion import iter_tags
from roundtrip import JAVA, swf_body
from pilot_resource import ROOT
from skin_recipe import recipe_edits


def make_candidate(source, work, java_file, expected_size):
    original = source.read_bytes()
    if len(original) != expected_size:
        raise ValueError(f"Expected an archived original of {expected_size} bytes")
    body = swf_body(original)
    with (work / "patch.log").open("wb") as log:
        subprocess.run([JAVA, "-cp", str(ROOT / "toolchain/ffdec/lib/*"),
                        Path(__file__).with_name(java_file).resolve(), source,
                        work / "original.abc", work / "patched.abc"],
                       stdout=log, stderr=subprocess.STDOUT, check=True)
    [(offset, payload, raw)] = [(offset, payload, raw) for kind, offset, payload, raw in iter_tags(body)
                                if kind == 82]
    abc_start = payload.index(0, 4) + 1
    if (work / "original.abc").read_bytes() != payload[abc_start:]:
        raise ValueError("FFDec did not losslessly read the original ABC")
    new_payload = payload[:abc_start] + (work / "patched.abc").read_bytes()
    new_tag = struct.pack("<HI", (82 << 6) | 63, len(new_payload)) + new_payload
    new_body = body[:offset] + new_tag + body[offset + len(raw):]
    fws_source = b"FWS" + original[3:8] + body
    candidate = b"FWS" + original[3:4] + struct.pack("<I", len(new_body) + 8) + new_body
    return fws_source, candidate


def reviewed_table(original, candidate, script_name, version):
    def rust_bytes(data):
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
        if len(rows) > 1:
            return "&[\n        " + ",\n        ".join(rows) + ",\n    ]"
        return "&[" + "".join(rows) + "]"

    edits = recipe_edits(original, candidate)
    lines = [f"// Generated by src/tools/swf-patches/{script_name} from version {version}.",
             "// Offsets are relative to the beginning of the uncompressed FWS file.",
             "#[rustfmt::skip]", "pub(super) const EDITS: &[(usize, &[u8], &[u8])] = &["]
    for pos, old, new in edits:
        lines.append(f"    ({pos}, {rust_bytes(old)}, {rust_bytes(new)}),")
    return "\n".join([*lines, "];", ""])


def build(script_name, version, reference, expected_size, java_file, table_name, bundle_name, candidate_name):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=reference)
    parser.add_argument("--output-dir", type=Path, required=True, help="A fresh build directory")
    parser.add_argument("--emit-table", action="store_true",
                        help="Write the reviewed Rust table instead of comparing it")
    args = parser.parse_args()
    work = args.output_dir.resolve()
    work.mkdir(exist_ok=False, parents=True)
    source = args.source.resolve(strict=True)
    original, candidate = make_candidate(source, work, java_file, expected_size)
    table = reviewed_table(original, candidate, script_name, version)
    table_path = ROOT / "src/optimization/engine/frontend-utils/src/backends/navigator" / table_name
    if args.emit_table:
        table_path.write_bytes(table.encode())
    elif table != table_path.read_text(encoding="utf-8"):
        raise ValueError("Candidate differs from the reviewed display patch")
    bundle = work / bundle_name
    bundle.mkdir()
    shutil.copyfile(source, bundle / "original.swf")
    (bundle / candidate_name).write_bytes(candidate)
    print(bundle)
